// Generates docs/generated/symbol-index.md — top-level symbols of src/LifeManager.jsx with line and section.
const fs = require("fs");
const path = require("path");
const S = require("./lib/source");

const src = S.readSrc();
const decls = S.collectDecls(src.text).filter((d) => d.kind !== "destructure");
const regions = S.dataRegions(src);
const rows = decls.map((d) => {
  const kind = S.DATA_TABLES.includes(d.name) ? "data" : /^[A-Z][A-Za-z]+$/.test(d.name) && d.kind === "function" ? "component" : d.kind === "function" ? "function" : /^[A-Z_]+$/.test(d.name) ? "const" : "const";
  return `| \`${d.name}\` | ${kind} | ${d.line} | ${S.sectionOf(src.lines, d.line) || "-"} |`;
});
const out = `<!-- GENERATED by tools/harness/gen-symbol-index.js from src/LifeManager.jsx — do not edit by hand --><!-- src: SPEC-A -->
# Symbol index

Top-level declarations of \`src/LifeManager.jsx\` (${src.lines.length} lines, ${decls.length} symbols). Use these names as grep anchors; line numbers drift — the section column is the stable locator.

Data-table regions (skipped by duplicate detection, frozen by rules 6/15): ${regions.map((r) => `\`${r.name}\` ${r.start}–${r.end}`).join(", ")}.

| Symbol | Kind | Line | Section |
|---|---|---|---|
${rows.join("\n")}
`;
const dest = path.join(S.ROOT, "docs", "generated", "symbol-index.md");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`symbol-index.md: ${decls.length} symbols`);
