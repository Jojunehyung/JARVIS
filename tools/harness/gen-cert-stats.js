// Generates the data-table appendices under docs/generated/ from src/LifeManager.jsx:
// cert-table.md, exam-table.md, weight-matrix.md, onboarding-tables.md. Asserts row counts from finish.config.json.
const fs = require("fs");
const path = require("path");
const S = require("./lib/source");

const src = S.readSrc();
const get = (n) => { try { return S.evalConst(n, src); } catch (e) { return undefined; } };
const CERTS = get("CERTS"), CERT_CATS = get("CERT_CATS"), EXAMS = get("EXAMS"), WEIGHT_MATRIX = get("WEIGHT_MATRIX");
const CERT_W_EXC = get("CERT_W_EXC"), DIR_ALIAS = get("DIR_ALIAS"), DIR_CATS = get("DIR_CATS"), TIER_MULT = get("TIER_MULT");
const certP = (d) => Math.round((0.2 * d * d) / 10) * 10;
const achGrade = (d) => (d >= 82 ? "A" : d >= 65 ? "B" : d >= 50 ? "C" : d >= 35 ? "D" : "E");
const avg = (a) => (a.reduce((s, x) => s + x, 0) / a.length).toFixed(2);
const HEAD = (script, id) => `<!-- GENERATED by tools/harness/${script} from src/LifeManager.jsx — do not edit by hand --><!-- src: ${id} -->\n`;
const esc = (s) => String(s).replace(/\|/g, "\\|");
const OUT = path.join(S.ROOT, "docs", "generated");
fs.mkdirSync(OUT, { recursive: true });

const cfg = (() => { try { return require("./finish.config.json").expectedCounts; } catch { return null; } })();
const assertCount = (label, got, want) => { if (cfg && want !== undefined && got !== want) { console.error(`gen-cert-stats: ${label} count ${got} ≠ expected ${want} — update finish.config.json expectedCounts if the change is intentional`); process.exit(1); } };
assertCount("CERTS", CERTS.length, cfg?.certs);
assertCount("EXAMS", EXAMS.length, cfg?.examFamilies);
assertCount("WEIGHT_MATRIX jobs", Object.keys(WEIGHT_MATRIX).length, cfg?.jobs);
assertCount("CERT_CATS", CERT_CATS.length, cfg?.categories);
assertCount("CERT_W_EXC", Object.keys(CERT_W_EXC).length, cfg?.exceptions);

/* ── cert-table.md ── */
{
  const byCat = {}; for (const c of CERTS) (byCat[c.c] = byCat[c.c] || []).push(c);
  const grade = { A: 0, B: 0, C: 0, D: 0, E: 0 }; for (const c of CERTS) grade[achGrade(c.d)]++;
  const dec = {}; for (const c of CERTS) { const k = c.d === 100 ? "100" : `${Math.floor(c.d / 10) * 10}–${Math.floor(c.d / 10) * 10 + 9}`; dec[k] = (dec[k] || 0) + 1; }
  const sgs = {}; for (const c of CERTS) if (c.sg) (sgs[c.sg] = sgs[c.sg] || []).push(c);
  const lv = {}; for (const c of CERTS) lv[c.l] = (lv[c.l] || 0) + 1;
  let md = HEAD("gen-cert-stats.js", "SPEC-B") + `# Certification table (\`CERTS\`, ${CERTS.length} entries)\n\nColumns: name (Korean, as issued) · D = raw difficulty 20–100 · sg/st = stage group / step (differential payout, [Rule 3](../design-docs/core-beliefs.md#rule-3)) · level · P = certP(D) = round(0.2·D²/10)·10 · grade ([Rule 5](../design-docs/core-beliefs.md#rule-5)). Numeric values are frozen ([Rule 6](../design-docs/core-beliefs.md#rule-6)).\n\n`;
  md += `## Statistics\n\n- Categories (${CERT_CATS.length}): ${CERT_CATS.map((c) => `${c} ${(byCat[c] || []).length}`).join(" · ")}\n- Grade distribution: E ${grade.E} / D ${grade.D} / C ${grade.C} / B ${grade.B} / A ${grade.A}\n- D by decade: ${Object.entries(dec).sort().map(([k, v]) => `${k}: ${v}`).join(" · ")}\n- D min ${Math.min(...CERTS.map((c) => c.d))} · max ${Math.max(...CERTS.map((c) => c.d))} · mean ${avg(CERTS.map((c) => c.d))}\n- Levels: ${Object.entries(lv).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(" · ")}\n- Stage groups (${Object.keys(sgs).length}): ${Object.entries(sgs).map(([k, v]) => `${k} ${v.length}`).join(" · ")}\n\n`;
  for (const cat of CERT_CATS) {
    const arr = byCat[cat] || []; if (!arr.length) continue;
    md += `## ${cat} (${arr.length})\n\n| Name | D | sg/st | Level | P | Grade |\n|---|---|---|---|---|---|\n`;
    for (const c of arr) md += `| ${esc(c.n)} | ${c.d} | ${c.sg ? `${c.sg}/${c.st}` : "-"} | ${c.l} | ${certP(c.d)} | ${achGrade(c.d)} |\n`;
    md += "\n";
  }
  fs.writeFileSync(path.join(OUT, "cert-table.md"), md);
}

/* ── exam-table.md ── */
{
  let md = HEAD("gen-cert-stats.js", "SPEC-C") + `# Exam families (\`EXAMS\`, ${EXAMS.length})\n\nBands: label / D / P / conf (conf = evidence confidence of the calibration, not an achievement grade). Payout follows [Rule 2](../design-docs/core-beliefs.md#rule-2): band snapshot, same-family difference only, per-language skill-bucket decay, specialisation at D75+.\n\n`;
  const exceptions = [];
  for (const e of EXAMS) {
    md += `## ${e.n} (\`${e.id}\`) — ${e.cat || ""} · lang ${e.lang || "-"} · dim ${e.dim || "-"}\n\n| Band | D | P | conf |\n|---|---|---|---|\n`;
    for (const b of e.bands || []) { md += `| ${esc(b[0])} | ${b[1]} | ${b[2]} | ${b[3] ?? "-"} |\n`; if (b[2] !== certP(b[1])) exceptions.push(`${e.n} ${b[0]}: P ${b[2]} ≠ certP(${b[1]}) = ${certP(b[1])}`); }
    md += "\n";
  }
  md += `## Bands whose P deviates from certP(D)\n\n${exceptions.length ? exceptions.map((x) => `- ${x}`).join("\n") : "- none"}\n`;
  fs.writeFileSync(path.join(OUT, "exam-table.md"), md);
}

/* ── weight-matrix.md ── */
{
  const jobs = Object.keys(WEIGHT_MATRIX);
  let md = HEAD("gen-cert-stats.js", "SPEC-D") + `# Job-fit weighting (\`WEIGHT_MATRIX\` ${jobs.length}×${CERT_CATS.length}, \`CERT_W_EXC\`, \`DIR_ALIAS\`, \`DIR_CATS\`)\n\nTier multipliers \`TIER_MULT\`: ${Object.entries(TIER_MULT).map(([k, v]) => `${k} ${v}`).join(" · ")}. Unlisted cell = C (×0). Policy and evidence rules: [Rule 15](../design-docs/core-beliefs.md#rule-15), [job-weighting.md](../design-docs/job-weighting.md).\n\n`;
  md += `| Job | ${CERT_CATS.map((c) => esc(c)).join(" | ")} |\n|---|${CERT_CATS.map(() => "---").join("|")}|\n`;
  for (const j of jobs) md += `| ${esc(j)} | ${CERT_CATS.map((c) => WEIGHT_MATRIX[j][c] || "C").join(" | ")} |\n`;
  md += `\n## Individual exceptions (\`CERT_W_EXC\`, ${Object.keys(CERT_W_EXC).length} certs)\n\n| Cert | Job → tier |\n|---|---|\n`;
  for (const [n, v] of Object.entries(CERT_W_EXC)) md += `| ${esc(n)} | ${Object.entries(v).map(([j, t]) => `${esc(j)} ${t}`).join(", ")} |\n`;
  md += `\n## Knowledge-direction aliases (\`DIR_ALIAS\`)\n\n${Object.entries(DIR_ALIAS).map(([a, j]) => `- ${a} → ${j}`).join("\n")}\n\n## Recommended categories per direction (\`DIR_CATS\`)\n\n| Direction | Categories | Exam |\n|---|---|---|\n`;
  for (const [k, v] of Object.entries(DIR_CATS)) md += `| ${esc(k)} | ${(v.cats || []).map(esc).join(", ") || "-"} | ${v.exam ? "yes" : ""} |\n`;
  fs.writeFileSync(path.join(OUT, "weight-matrix.md"), md);
}

/* ── onboarding-tables.md ── */
{
  const names = ["AGE_OPTS", "STATUS_OPTS", "EDU_OPTS", "MAJOR_FIELDS", "KNOWLEDGE_FIELDS", "CAREER_OPTS", "LEAD_OPTS", "BIZ_OPTS", "OUTPUT_OPTS", "JOB_FIELDS", "GATE_CHIPS", "TASK_TEMPLATES", "STUDY_REQ", "RANKS", "DIFFS", "AREA_PRESETS", "ROLE_PRESETS"];
  let md = HEAD("gen-cert-stats.js", "SPEC-E") + `# Onboarding and rule tables\n\nOption lists and rule tables as defined in source. Korean values are UI copy and stay Korean.\n\n`;
  for (const n of names) {
    const v = get(n); if (v === undefined) continue;
    md += `## \`${n}\`\n\n`;
    if (Array.isArray(v)) {
      if (v.length && typeof v[0] === "object") { const cols = [...new Set(v.flatMap((o) => Object.keys(o)))]; md += `| ${cols.join(" | ")} |\n|${cols.map(() => "---").join("|")}|\n`; for (const o of v) md += `| ${cols.map((c) => esc(JSON.stringify(o[c]) ?? "")).join(" | ")} |\n`; }
      else md += v.map((x) => `- ${esc(x)}`).join("\n") + "\n";
    } else if (typeof v === "object") { md += `| Key | Value |\n|---|---|\n`; for (const [k, x] of Object.entries(v)) md += `| ${esc(k)} | ${esc(JSON.stringify(x))} |\n`; }
    md += "\n";
  }
  fs.writeFileSync(path.join(OUT, "onboarding-tables.md"), md);
}
console.log(`generated: cert-table (${CERTS.length}), exam-table (${EXAMS.length}), weight-matrix (${Object.keys(WEIGHT_MATRIX).length}×${CERT_CATS.length}), onboarding-tables`);
